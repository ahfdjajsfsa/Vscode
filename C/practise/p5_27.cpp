// 题目描述

// 有一个箱子容量为 V（正整数，0<=V<=1000），同时有 n 个物品（0<n<=100），每个物品有一定的体积和价值。要求从 n
// 个物品中任选若干个装入箱内，在箱子能放得下的前提下，使箱子内物品的总价值最大。

// 输入描述

// 一个正整数 V，表示箱子容量。

// 一个正整数 n，表示物品数量。

// 接下来 n 行，每行输入两个不超过 1000 的正整数，分别表示物品的体积和价值。

// 输出描述

// 输出一个整数，表示箱子能装下的最大价值。

// 样例输入

// 3
// 2
// 2 100
// 4 200

// 样例输出

// 100

// 样例解释

// 输入：

// 3    // 箱子的总容量为 3

// 2    // 一共有 2 个物品

// 2 100    // 第 1 个物品体积为 2，价值为 100

// 4 200    // 第 2 个物品体积为 4，价值为 200

// 输出：

// 100

// 在箱子容量允许的前提下，应选择第 1 个物品，最大价值为 100。

// 数据规模

// 对于前 3 个测试点：

// 0<n,V<=10

// 对于第 4 个测试点：

// 0<n<=100
// 0<V<=1000

#include <bits/stdc++.h>
using namespace std;

int main()
{
    int V, n;
    // 读入箱子容量和物品数量
    cin >> V >> n;

    // dp数组，大小为V+1，初始全为0
    vector<int> dp(V + 1, 0);

    for (int i = 0; i < n; ++i)
    {
        int w, v;
        cin >> w >> v;

        // 逆序遍历容量，防止物品被重复放入
        for (int j = V; j >= w; --j)
        {
            dp[j] = max(dp[j], dp[j - w] + v);
        }
    }

    // 输出容量为V时的最大价值
    cout << dp[V] << endl;

    return 0;
}