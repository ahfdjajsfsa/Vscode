// 题目描述

// 有 n 个狐獴，个头各不相同。现在从中任意选取 m（m ≤
// n）只狐獴排成一个序列，且要求序列里狐獴的个头必须是降序。问这样的序列一共有多少种？

// 输入描述

// 输入第一行包括两个正整数 n, m，用空格隔开，代表狐獴的个数和选取的个数。

// 输入第二行包括 n 个各不相同的正整数，用空格隔开，代表 n 个狐獴的个头。

// 输出描述

// 输出所能形成的长度为 m 且降序的序列个数。

// 样例输入

// 4 2
// 1 3 4 2

// 样例输出

// 6

// 样例解释

// 可以形成的长度为 2 且降序的序列包括：

// 4 3
// 4 2
// 4 1
// 3 2
// 3 1
// 2 1

// 测试点和数据规模说明

// 对于前两个测试点：

// 1 ≤ m ≤ n ≤ 4

// 对于第三个测试点：

// 1 ≤ m ≤ n ≤ 8

// 对于第四个测试点：

// 1 ≤ m ≤ n ≤ 12

int fun(int a)
{
    if (a == 1)
        return 1;
    if (a == 0)
        return 1;
    else
        return a * fun(a - 1);
}

#include <bits/stdc++.h>
using namespace std;

int main()
{
    int n, m;
    cin >> n >> m;
    int a[n];
    for (int i = 0; i < n; i++)
        cin >> a[i];
    cout << fun(n) / fun(m) / fun(n - m);
}